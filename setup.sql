SELECT a.email, u.nickname, COUNT(h.history_id) AS sessions
FROM auth.users a
LEFT JOIN kiwoom.user_info u    ON u.user_id = a.id
LEFT JOIN kiwoom.study_history h ON h.user_id = a.id
GROUP BY a.email, u.nickname
ORDER BY a.email;
