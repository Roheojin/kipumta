-- ------------------------------------------------------------
-- 8. 예시 데이터
--    study_history가 비어 있을 때만 들어갑니다.
--    날짜는 실행 시점 기준 상대 시각이라 언제 돌려도 최근 데이터가 됩니다.
-- ------------------------------------------------------------

INSERT INTO kiwoom.study_history (user_id, subject, start_time, end_time, study_minutes)
SELECT
    b.user_id,
    (ARRAY['SQLD', '컴활', '파이썬', '금융투자분석사'])[b.subj_idx + 1],
    b.start_ts,
    b.start_ts + make_interval(mins => b.dur),
    b.dur
FROM (
    SELECT
        a.id AS user_id,
        (abs(hashtext(a.id::text || d::text)) % 4)        AS subj_idx,
        45 + (abs(hashtext(a.id::text || d::text || 'm')) % 150) AS dur,
        date_trunc('day', now() - make_interval(days => d))
            + make_interval(hours => 9 + (abs(hashtext(a.id::text || d::text || 'h')) % 11)) AS start_ts
    FROM auth.users a
    CROSS JOIN generate_series(1, 21) AS d
    WHERE (abs(hashtext(a.id::text || d::text || 'x')) % 10) < 7
) b
WHERE NOT EXISTS (SELECT 1 FROM kiwoom.study_history);


